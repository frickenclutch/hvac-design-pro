// Tenant branding on PDF reports.
//
// Every calculation report (Manual J / D / S, AED, Combined) starts its content
// at y ≥ 50pt, which leaves the top strip of each page free. `stampTenantBrand`
// is a post-pass that runs just before `doc.save()` and puts the tenant's logo
// and name in the top-right of that strip on every page. Being a post-pass, it
// needs no knowledge of each report's layout and cannot disturb its content —
// these are permit-facing documents, so the body is left exactly as generated.
//
// Report TEXT that names the software (disclaimers, the PE attestation, print
// views) goes through `reportProductName()` below: the platform's name, or a
// white-labelled tenant's. The engine version stamp is never rebranded.

import type { jsPDF } from 'jspdf';
import { useAuthStore } from '../auth/store/useAuthStore';
import { useBrandingStore, orgLogoUrl, PLATFORM_NAME, productName } from '../../stores/useBrandingStore';
import { buildPalette } from '../../lib/tenantTheme';
import { usePreferencesStore } from '../../stores/usePreferencesStore';
import { brandMarkLayout } from './brandMarkLayout';

export interface TenantPdfBrand {
  name: string;
  /** RGB for the name on white paper — the brand's -700 shade, or null for ink. */
  color: [number, number, number] | null;
  logo: { dataUrl: string; aspect: number } | null;
  whiteLabel: boolean;
}

export const PLATFORM_WATERMARK = 'GENERATED BY HVAC DESIGNPRO';

/** Default watermark text when the user has not typed their own. A
 *  white-labelled tenant's reports carry the tenant's name instead.
 *  Synchronous (reads the store) so the sync CAD plot generator can use it. */
export function defaultWatermark(): string {
  const b = useBrandingStore.getState().branding;
  return b.whiteLabel && b.displayName ? `GENERATED BY ${b.displayName.toUpperCase()}` : PLATFORM_WATERMARK;
}

/** The watermark to print. The preference ships pre-filled with the platform
 *  default, so "left at the default" has to count as "not customised" — else a
 *  white-labelled tenant's reports would still carry the platform watermark.
 *  A watermark the user actually typed always wins. */
export function resolveWatermark(prefText: string | null | undefined): string {
  const typed = (prefText ?? '').trim();
  return !typed || typed.toUpperCase() === PLATFORM_WATERMARK ? defaultWatermark() : typed;
}

/** The software's name as printed in report disclaimers, attestations and the
 *  print views. Per the platform owner (2026-11-24): a white-labelled tenant's
 *  documents use the tenant's name here too. The engine version stamped on
 *  each report is unaffected and remains the traceability anchor. */
export function reportProductName(): string {
  return productName();
}

function hexToRgb(hex: string): [number, number, number] {
  return [1, 3, 5].map((i) => parseInt(hex.slice(i, i + 2), 16)) as [number, number, number];
}

// Logo pixels, cached per logo key for the session — a report export should
// not re-download the logo every time.
const logoCache = new Map<string, { dataUrl: string; aspect: number } | null>();

/** Read the public logo into a PNG data URL via a CORS-enabled <img> + canvas.
 *  Resolves null on any failure (offline, blocked, bad image): a report must
 *  never fail to export because a logo could not be fetched. */
function loadLogo(url: string): Promise<{ dataUrl: string; aspect: number } | null> {
  return new Promise((resolve) => {
    const done = (v: { dataUrl: string; aspect: number } | null) => resolve(v);
    try {
      const img = new Image();
      img.crossOrigin = 'anonymous';
      const timer = setTimeout(() => done(null), 4000);
      img.onload = () => {
        clearTimeout(timer);
        try {
          const canvas = document.createElement('canvas');
          canvas.width = img.naturalWidth;
          canvas.height = img.naturalHeight;
          const ctx = canvas.getContext('2d');
          if (!ctx || !img.naturalWidth || !img.naturalHeight) return done(null);
          ctx.drawImage(img, 0, 0);
          done({ dataUrl: canvas.toDataURL('image/png'), aspect: img.naturalWidth / img.naturalHeight });
        } catch {
          done(null); // tainted canvas / encode failure
        }
      };
      img.onerror = () => { clearTimeout(timer); done(null); };
      // A distinct URL from the one the app shell's plain <img> uses, so the
      // browser never answers this CORS request from a non-CORS cache entry.
      img.src = `${url}&cors=1`;
    } catch {
      done(null);
    }
  });
}

/** The active tenant's brand for a report, or null when the tenant has set no
 *  name or logo (reports then look exactly as they always have). */
export async function loadTenantPdfBrand(): Promise<TenantPdfBrand | null> {
  const org = useAuthStore.getState().organisation;
  const branding = useBrandingStore.getState().branding;
  if (!org || (!branding.displayName && !branding.logoKey)) return null;

  let logo: TenantPdfBrand['logo'] = null;
  const url = orgLogoUrl(org.id, branding.logoKey);
  if (url && branding.logoKey) {
    if (!logoCache.has(branding.logoKey)) logoCache.set(branding.logoKey, await loadLogo(url));
    logo = logoCache.get(branding.logoKey) ?? null;
    // Don't pin a transient failure for the whole session.
    if (!logo) logoCache.delete(branding.logoKey);
  }

  const palette = buildPalette(branding.primaryColor);
  return {
    name: branding.displayName ?? org.name ?? PLATFORM_NAME,
    color: palette ? hexToRgb(palette[700]) : null,
    logo,
    whiteLabel: branding.whiteLabel,
  };
}

/** Stamp the tenant mark on every page. Works for any jsPDF unit (the report
 *  generators use `pt`; this converts regardless). No-op for a null brand. */
export function stampTenantBrand(doc: jsPDF, brand: TenantPdfBrand | null): void {
  if (!brand) return;
  const prefs = usePreferencesStore.getState();
  const side = prefs.firmStampDataUrl && prefs.firmStampPosition === 'top-right' ? 'left' : 'right';
  // jsPDF: scaleFactor = points per document unit.
  const k = doc.internal.scaleFactor;
  const u = (pt: number) => pt / k;
  const pages = doc.getNumberOfPages();
  for (let p = 1; p <= pages; p++) {
    doc.setPage(p);
    doc.setFont('helvetica', 'bold');
    doc.setFontSize(9);
    const nameWidthPt = doc.getTextWidth(brand.name) * k;
    const pageWidthPt = doc.internal.pageSize.getWidth() * k;
    const m = brandMarkLayout(pageWidthPt, brand.logo?.aspect ?? null, nameWidthPt, side);
    if (brand.logo) {
      try {
        doc.addImage(brand.logo.dataUrl, 'PNG', u(m.logoX), u(m.logoY), u(m.logoW), u(m.logoH));
      } catch { /* a bad image must not cost the user their report */ }
    }
    if (brand.color) doc.setTextColor(brand.color[0], brand.color[1], brand.color[2]);
    else doc.setTextColor(30, 41, 59);
    doc.text(brand.name, u(m.nameX), u(m.nameBaseline));
  }
  doc.setTextColor(0, 0, 0);
}
